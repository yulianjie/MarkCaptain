const actionKeys: Record<AgentWritingCommand, AgentM1Key> = {
  polish: 'promptPolish', shorten: 'promptShorten', continue: 'promptContinue',
  translate: 'promptTranslate', explain: 'promptExplain', terms: 'promptTerms', structure: 'promptStructure',
}

export function agentM1Copy(locale: string, key: AgentM1Key, params?: Record<string, string | number>): string {
  const language = locale in copy ? locale as keyof typeof copy : 'en'
  const template = copy[language][key] ?? copy.en[key]
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params?.[name] ?? `{${name}}`))
}

export function agentWritingCommandPrompt(command: AgentWritingCommand, locale: string): string {
  return agentM1Copy(locale, actionKeys[command])
}

export function agentWritingCommandLabel(command: AgentWritingCommand, locale: string): string {
  const labelKeys: Record<AgentWritingCommand, AgentM1Key> = {
    polish: 'commandPolish', shorten: 'commandShorten', continue: 'commandContinue',
    translate: 'commandTranslate', explain: 'commandExplain', terms: 'commandTerms', structure: 'commandStructure',
  }
  return agentM1Copy(locale, labelKeys[command])
}
